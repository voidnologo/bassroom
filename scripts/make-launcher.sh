#!/usr/bin/env bash
#
# Build the Bassroom.app launcher into ~/Applications, so the app can be
# started from the Dock, Finder, or Spotlight instead of a remembered command.
#
# The bundle holds no logic of its own: it opens a terminal window on the
# repo's ./start script, which keeps one definition of how Bassroom starts and
# leaves the dev server's output where it can be read and Ctrl-C'd.
#
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# The app serves this as its favicon; the launcher renders the same file so
# the icon in the Dock and the icon in the browser tab cannot drift apart.
ICON_SVG="$REPO/app/public/icon.svg"
START_SCRIPT="$REPO/start"

APP_NAME="Bassroom"
DEST_DIR="${BASSROOM_LAUNCHER_DEST:-$HOME/Applications}"
BUNDLE="$DEST_DIR/$APP_NAME.app"
# Terminal.app is the one that is always installed. Set BASSROOM_TERMINAL_APP
# to iTerm or Ghostty and re-run to use that instead.
TERMINAL_APP="${BASSROOM_TERMINAL_APP:-Terminal}"
LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister

ICON_SIZES=(16 32 64 128 256 512 1024)

# Set in main, read by the EXIT trap after main's locals are gone.
WORKDIR=""

die() {
  printf 'make-launcher: %s\n' "$*" >&2
  exit 1
}

# rsvg-convert renders the SVG faithfully; sips is the fallback that needs no
# Homebrew install but handles SVG less predictably.
render_png() {
  local size="$1" out="$2"
  command -v rsvg-convert >/dev/null 2>&1 \
    && { rsvg-convert -w "$size" -h "$size" "$ICON_SVG" -o "$out"; return 0; }
  sips -s format png --resampleHeightWidth "$size" "$size" "$ICON_SVG" --out "$out" >/dev/null \
    || die "neither rsvg-convert nor sips could render $ICON_SVG (brew install librsvg)."
}

build_icns() {
  local iconset="$1" size
  mkdir -p "$iconset"
  for size in "${ICON_SIZES[@]}"; do
    render_png "$size" "$iconset/size-$size.png"
  done
  # iconutil only accepts this exact naming, and only these pairings.
  cp "$iconset/size-16.png" "$iconset/icon_16x16.png"
  cp "$iconset/size-32.png" "$iconset/icon_16x16@2x.png"
  cp "$iconset/size-32.png" "$iconset/icon_32x32.png"
  cp "$iconset/size-64.png" "$iconset/icon_32x32@2x.png"
  cp "$iconset/size-128.png" "$iconset/icon_128x128.png"
  cp "$iconset/size-256.png" "$iconset/icon_128x128@2x.png"
  cp "$iconset/size-256.png" "$iconset/icon_256x256.png"
  cp "$iconset/size-512.png" "$iconset/icon_256x256@2x.png"
  cp "$iconset/size-512.png" "$iconset/icon_512x512.png"
  cp "$iconset/size-1024.png" "$iconset/icon_512x512@2x.png"
  rm -f "$iconset"/size-*.png
  iconutil -c icns "$iconset" -o "$BUNDLE/Contents/Resources/$APP_NAME.icns"
}

write_plist() {
  cat >| "$BUNDLE/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$APP_NAME</string>
  <key>CFBundleDisplayName</key><string>$APP_NAME</string>
  <key>CFBundleIdentifier</key><string>io.telegraph.bassroom.launcher</string>
  <key>CFBundleExecutable</key><string>$APP_NAME</string>
  <key>CFBundleIconFile</key><string>$APP_NAME</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST
}

write_executable() {
  local exe="$BUNDLE/Contents/MacOS/$APP_NAME"
  cat >| "$exe" <<LAUNCH
#!/bin/bash
# Generated by scripts/make-launcher.sh — edit that, not this.
exec /usr/bin/open -a "$TERMINAL_APP" "$START_SCRIPT"
LAUNCH
  chmod +x "$exe"
}

main() {
  [ -f "$ICON_SVG" ] || die "icon source missing: $ICON_SVG"
  [ -x "$START_SCRIPT" ] || die "start script missing or not executable: $START_SCRIPT"
  open -Ra "$TERMINAL_APP" >/dev/null 2>&1 || die "no application named '$TERMINAL_APP' is installed."

  rm -rf "$BUNDLE"
  mkdir -p "$BUNDLE/Contents/MacOS" "$BUNDLE/Contents/Resources"
  write_plist
  write_executable

  WORKDIR="$(mktemp -d)"
  trap 'rm -rf "${WORKDIR:-}"' EXIT
  build_icns "$WORKDIR/$APP_NAME.iconset"

  # Finder caches bundles by mtime, and Spotlight only offers what Launch
  # Services knows about, so a rebuilt bundle has to announce itself.
  touch "$BUNDLE"
  [ -x "$LSREGISTER" ] && "$LSREGISTER" -f "$BUNDLE" >/dev/null 2>&1

  echo "Built $BUNDLE"
  echo "It opens $TERMINAL_APP on $START_SCRIPT. Spotlight: type \"$APP_NAME\"."
}

main "$@"
